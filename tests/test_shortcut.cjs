const fs = require('fs');
const assert = require('assert');
let callback, focused, launched = 0, windows = [];
let registration;
const GLib = {PRIORITY_DEFAULT: 0, SOURCE_REMOVE: false, timeout_add(p,t,cb) {registration = cb; return 1;}, Source: {remove() {}}};
const settings = {get_string: () => '<Control><Shift>g', set_string() {}};
let binding = '<Control><Shift>g';
const Gio = {Settings: class {get_string() {return binding;} set_string(k, v) {binding = v;}}};
const Extension = class {getSettings() {return settings;}};
const Meta = {KeyBindingFlags: {IGNORE_AUTOREPEAT: 1}, KeyBindingAction: {NONE: 0}, TabList: {NORMAL_ALL: 0}};
const app = {get_windows: () => [], activate: () => launched++};
const Shell = {ActionMode: {NORMAL: 1, OVERVIEW: 2, POPUP: 4}, AppSystem: {get_default: () => ({lookup_app: () => app})}};
const Main = {wm: {addKeybinding(k, s, f, modes, cb) {assert.equal(modes, 7); callback = cb; return 1;}, removeKeybinding() {}}, overview: {hide() {}}, activateWindow(w) {focused = w;}, notifyError() {throw Error('Unexpected missing app');}};
const global = {display: {get_tab_list: () => windows}, get_current_time: () => 123};
const source = fs.readFileSync(require('path').join(__dirname, '../gnome-extension/extension.js'), 'utf8').replace(/^import .*;\n/gm, '').replace('export default class', 'class');
const C = new Function('GLib', 'Gio', 'Extension', 'Meta', 'Shell', 'Main', 'global', source + '\nreturn DictationShortcut;')(GLib, Gio, Extension, Meta, Shell, Main, global);
const extension = new C();
extension.enable();
registration();
assert.equal(binding, '');
callback();
assert.equal(launched, 1);
windows = [{get_wm_class: () => 'unrelated-app'}, {get_wm_class: () => 'local.whisper.Dictation'}];
callback();
assert.equal(focused, windows[1]);
assert.equal(launched, 1);
extension.disable();
assert.equal(binding, '<Control><Shift>g');
console.log('PASS: global binding, initial launch, existing-window focus, and restoration on disable');
